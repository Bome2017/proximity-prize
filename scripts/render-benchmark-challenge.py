#!/usr/bin/env python3
"""Render the exact trusted Comparator statement for either track."""

from __future__ import annotations

import sys

from benchmark_contract import (
    atomic_write_text,
    parse_centibits,
    parse_radius,
    parse_unsafe_index,
)


def main() -> None:
    if len(sys.argv) != 5:
        raise SystemExit(
            "usage: render-benchmark-challenge.py "
            "lower|upper CENTIBITS CLAIM OUTPUT"
        )

    profile, raw_score, claim, output = sys.argv[1:]
    if profile not in {"lower", "upper"}:
        raise SystemExit(f"unknown benchmark profile: {profile}")
    try:
        centibits = parse_centibits(raw_score)
        if profile == "lower":
            numerator, denominator = parse_radius(claim)
            source = f"""
/- Generated by scripts/render-benchmark-challenge.py. Do not edit. -/
import ProximityPrize.Benchmark.TargetLower

namespace ProximityPrize.Benchmark

theorem candidate : ProtocolClaim {centibits} {numerator} {denominator} := by
  sorry

end ProximityPrize.Benchmark
""".lstrip()
        else:
            unsafe_index = parse_unsafe_index(claim)
            source = f"""
/- Generated by scripts/render-benchmark-challenge.py. Do not edit. -/
import ProximityPrize.Benchmark.TargetUpper

namespace ProximityPrize.Benchmark.Upper

theorem candidate : ProtocolClaimUpper {centibits} {unsafe_index} := by
  sorry

end ProximityPrize.Benchmark.Upper
""".lstrip()
    except (OSError, ValueError) as error:
        raise SystemExit(str(error)) from error

    atomic_write_text(output, source)


if __name__ == "__main__":
    main()
